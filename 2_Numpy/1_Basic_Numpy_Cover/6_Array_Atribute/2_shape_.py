# Shape : Ye Basically Ye batata Hia Ki Haar Dimension me Kitne Items Hai 

import numpy as np

#Ex1:
a = np.array([1,2,3])
print(a.shape)    # (3,) Out put ayagea

#Ex2:
b = np.array([[1,2,3], [1,2,3]])
print(b.shape)    # (2, 3) Out put ayagea

#Ex3:
c = np.array([[[1,2,3]]])
print(c.shape)    # (1, 1, 3) Out put ayagea
