#Data Analysis ka matlab hota hai data ko collect, clean, organize aur examine karna taaki usse useful information aur insights nikale ja sakein.
# Simple language mein:
# Raw Data → Analysis → Information → Decision

# Example

# Maan lo ek online store ke paas sales data hai:
# | Product | Sales |
# | ------- | ----- |
# | Laptop  | 100   |
# | Mobile  | 250   |
# | Tablet  | 50    |

# Data analysis karke pata chal sakta hai:

# Sabse zyada bikne wala product kaunsa hai? → Mobile
# Sabse kam bikne wala product kaunsa hai? → Tablet
# Kis product par zyada focus karna chahiye?


# Data Analysis ke Main Steps

#1- Collect Data –  Data gather karna
#2- Clean Data –    Missing values, duplicates, errors remove karna
#3- Process Data –  Data ko organize aur transform karna
#4- Analyze Data –  Patterns aur trends find karna
#5- Visualize Data – Charts, graphs banana
#6- Interpret Results – Business ya problem ke liye conclusions nikalna

#> Python mein Common Libraries <
# Pandas → Data manipulation
# NumPy → Numerical operations
# Matplotlib → Basic plotting
# Seaborn → Statistical visualization
# Plotly → Interactive charts


# Data Analysis vs Data Science ?

